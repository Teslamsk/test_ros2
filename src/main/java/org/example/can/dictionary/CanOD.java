package org.example.can.dictionary;

/**
 * CANopen Object Dictionary (OD) — "меню настроек" привода.
 *
 * Представьте, что привод — это прибор с множеством регистров. Каждый
 * регистр имеет уникальный адрес (индекс + суб-индекс), через который
 * мы читаем или записываем данные.
 *
 * Аналогия: OD — это ящик с подписанными ящичками:
 *   0x6040.00 → "сюда пишите команду" (Control Word)
 *   0x607A.00 → "сюда пишите целевой угол" (Target Position)
 *   0x6041.00 → "отсюда читайте текущее состояние" (Status Word)
 *
 * Доступ к ящичкам осуществляется через SDO (медленно, по одному)
 * или PDO (быстро, в реальном времени).
 */
public enum CanOD {

    // ===== Записываемые (команды, настройки) =====

    /**
     * 0x6040 — Control Word (слово управления).
     *
     * Сюда мы _пишем_ команды: включить, отключить, аварийно
     * остановить, начать поиск нуля. Это "джойстик" привода.
     *
     * Значения: см. ControlWord (ENABLE, QUICK_STOP...).
     */
    CONTROL_WORD      (0x6040, 0x00),

    /**
     * 0x6060 — Mode of Operation (режим работы).
     *
     * Определяет, как мы управляем приводом: по позиции,
     * по скорости или по крутящему моменту.
     *
     * Значения: см. OperationMode (PROFILED_POSITION, TORQUE...).
     */
    MODE_OF_OPERATION (0x6060, 0x00),

    /**
     * 0x6071 — Target Torque (целевой крутящий момент).
     *
     * В режиме управления моментом сюда (через PDO) мы передаём
     * желаемое усилие в мН·м (или в "% от номинала").
     *
     * Когда использовать: когда привод в режиме TORQUE (HAND).
     */
    TARGET_TORQUE (0x6071, 0x00),

    /**
     * 0x607A — Target Position (целевая позиция).
     *
     * В режиме позиционирования сюда мы передаём желаемый угол
     * (в тиках). Привод сам построит траекторию и доберётся
     * до этой позиции с заданной плавностью.
     *
     * Это "куда ехать" — задаём угол, привод крутится сам.
     */
    TARGET_POSITION (0x607A, 0x00),

    /**
     * 0x6080 — Maximum Torque (максимальный крутящий момент).
     *
     * Глобальный лимит момента: привод не выдаст больше
     * данного усилия, независимо от режима или команды.
     * Используется для защиты механизма от перегрузки.
     *
     * Для нас: в режиме LOCKED = полный момент, в RELAXED = снижен.
     */
    MAX_TORQUE    (0x6080, 0x00),

    /**
     * 0x60CB — Position Window (позиционное окно).
     *
     * Зона "точности" в тиках. Если фактическое положение
     * оказалось в пределах ±Position Window от целевой —
     * считается "достигли" и ставится флаг Target Reached.
     *
     * Аналогия: "доехали, если рядом с точкой в пределах 1 см".
     * Если значение = 0 — строжайшая точность (ровно в цель).
     */
    POSITION_WINDOW (0x60CB, 0x00),

    /**
     * 0x60F1 — P-Gain (коэффициент пропорциональности).
     *
     * Параметр ПИД-регулятора: чем больше P-Gain, тем агрессивнее
     * привод реагирует на отклонение от целевой позиции.
     *
     * Высокий P-Gain → жёсткое удержание, но возможен перелёт.
     * Низкий P-Gain → мягкое удержание, можно повернуть рукой.
     *
     * Для нас: LOCKED = 300 (жёстко), RELAXED = 30 (мягко).
     */
    P_GAIN (0x60F1, 0x00),

    // ===== Читаемые из привода (Actual state) =====

    /**
     * 0x6041 — Status Word (слово состояния).
     *
     * Отсюда мы _читаем_ состояние привода: включен ли он,
     * рабочий, есть ли ошибка, достигнута ли целевая позиция.
     * Это "спидометр + лампочка Check Engine".
     *
     * Флаги: см. StatusWord (OPERATION_ENABLED, FAULT...).
     */
    STATUS_WORD       (0x6041, 0x00),

    /**
     * 0x6064 — Actual Position (фактическая позиция).
     *
     * Здесь привод сообщает свою текущую позицию (в тиках) по
     * данным энкодера. Это то, где двигатель находится в реальности.
     * Используется для обратной связи и подтверждения "доехали?".
     */
    ACTUAL_POSITION (0x6064, 0x00),

    /**
     * 0x6077 — Actual Torque (фактический крутящий момент).
     *
     * Текущий момент, который выдаёт двигатель.
     * В режиме позиционирования — это усилие удержания.
     * Полезно для диагностики: "двигатель перегружен?".
     */
    ACTUAL_TORQUE (0x6077, 0x00);

    private final int index;
    private final int subIndex;

    CanOD(int index, int subIndex) {
        this.index = index;
        this.subIndex = subIndex;
    }

    public int getIndex()     { return index; }
    public int getSubIndex()  { return subIndex; }

    /**
     * Форматирует индекс и суб-индекс в строку вида "0x6040.00".
     */
    public static String toHex(int index, int subIndex) {
        return String.format("0x%04X.%02X", index, subIndex);
    }

    @Override
    public String toString() {
        return name() + " (" + toHex(index, subIndex) + ")";
    }
}