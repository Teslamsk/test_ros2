package org.example.can.dictionary;

/**
 * Mode of Operation (0x6060) — "режим работы" привода.
 *
 * Определяет, какой вид управления используется: двигателем управляют
 * через позицию, скорость, крутящий момент или что-то другое.
 *
 * Можно провести аналогию с водителем:
 *   - "Position" — навигатор: "доедь до точки X".
 *   - "Velocity" — круиз-контроль: "держи скорость Y".
 *   - "Torque" — жми педаль в пол: "дай газ Z".
 *
 * Режим можно менять "на лету" (без выключения привода), но после
 * переключения нужно подождать, пока статус-слово подтвердит смену.
 *
 * Для нашего лидара интересны три режима:
 *   - PROFILED_POSITION — поворот к заданному углу.
 *   - TORQUE — нулевой момент, можно крутить рукой.
 *   - HOMING — поиск нуля.
 */
public enum OperationMode {

    /**
     * 0x00 — Profiled Position (профилированная позиция).
     *
     * Основной режим для нашего лидара. Мы задаём целевой угол,
     * а привод сам строит плавную траекторию: разгон → движение →
     * торможение. Не нужно вычислять ускорение вручную — драйвер
     * делает это внутри по заданным профилям (скорость, ускорение,
     * деcceleration).
     *
     * Целевая позиция задаётся через PDO (в реальном времени).
     * Привод "держит" позицию — если её не менять, двигатель
     * сохраняет угол, создавая усилие.
     *
     * Когда использовать: обычный поворот лидара к углу сканирования
     * (LOCKED и RELAXED режимы в CanController).
     */
    PROFILED_POSITION   (0x00),

    /**
     * 0x01 — Homing (поиск точки отсчёта).
     *
     * Двигатель ищет механический датчик (концевик/оптический датчик)
     * или запоминает текущую позицию как "ноль". После завершения
     * возврата домой координаты пересчитываются: текущая позиция = 0.
     *
     * При этом режим можно задать разные стратегии поиска:
     *   - движение вперёд до концевика,
     *   - движение назад до концевика,
     *   - "мягкий" вариант: текущая позиция объявляется нулём без движения.
     *
     * Когда использовать: после запуска — если нужно синхронизировать
     * механическую позицию с "нулём" в ПО. У нас используется команда
     * setZero() в CanController.
     */
    HOMING              (0x01),

    /**
     * 0x02 — Profiled Velocity (профилированная скорость).
     *
     * Двигатель вращается с заданной скоростью, пока мы не поменяем
     * её или не переключим режим. Можно дать команду +30 об/мин —
     * и двигатель плавно разгонится до этой скорости и будет держать.
     *
     * Когда использовать: непрерывное вращение (например, 360° скан
     * без остановок). Для дискретных поворотов не нужен.
     */
    PROFILED_VELOCITY   (0x02),

    /**
     * 0x03 — Profiled Torque (профилированный крутящий момент).
     *
     * Задаём крутящий момент, привод плавно разгоняет ток до нужного
     * значения. Двигатель создаёт постоянное усилие — но не держит
     * позицию и не контролирует скорость. Если на валик нет нагрузки,
     * двигатель будет разгоняться.
     *
     * Когда использовать: тесты привода, калибровка. Для лидара
     * обычно не применяется.
     */
    PROFILED_TORQUE     (0x03),

    /**
     * 0x04 — Torque / Current (скоростной режим момента).
     *
     * Как Profiled Torque, но без плавного профиля — момент
     * применяется "сразу" (step response). Быстрее, но без
     * мягкого разгона.
     *
     * Критично: если задать момент = 0, двигатель не сопротивляется
     * вращению, но драйвер включен — энкодер работает, позицию
     * можно считывать.
     *
     * Когда использовать: наш режим HAND — когда нужно повернуть
     * лидар рукой без сопротивления, но с сохранением связи
     * с приводом и возможностью мгновенно вернуться к работе.
     */
    TORQUE              (0x04),

    /**
     * 0x05 — Velocity (скоростной режим скорости).
     *
     * Как Profiled Velocity, но без плавного розгона — скорость
     * задаётся мгновенно.
     *
     * Когда использовать: редко, в специфичных сценариях
     * высокочастотного управления.
     */
    VELOCITY            (0x05),

    /**
     * 0x06 — Interpolated Position (интерполированная позиция).
     *
     * Мастер передаёт серию точек (буфер), и привод плавно
     * interpolates между ними. Полезно для сложных траекторий:
     * "проведи по дуге через 10 точек".
     *
     * Когда использовать: если нужно плавное сканирование
     * по нескольким углам без дерганья. Для простого
     * "поверни на угол X" не нужен.
     */
    INTERPOLATED_POS    (0x06),

    /**
     * 0x07 — Cyclical Synchronous Position (циклическая синхронная позиция).
     *
     * В каждый такт CANopen (обычно 1 мс) отправляется новая целевая
     * позиция через PDO. Позволяет строить произвольные траектории
     * с частотой шины.
     *
     * Когда использовать: если нужна высокая частота обновления
     * траектории (например, живая трассировка). Для лидара
     * с дискретными остановками проще PROFILED_POSITION.
     */
    CYCLIC_SYNC_POS     (0x07),

    /**
     * 0x08 — Cyclical Synchronous Velocity.
     *
     * Аналог CYCLIC_SYNC_POS, но для скорости. Каждая PDO-пачка
     * обновляет целевую скорость.
     *
     * Когда использовать: высокочастотное управление скоростью
     * из внешнего контроллера. Нам не требуется.
     */
    CYCLIC_SYNC_VEL     (0x08),

    /**
     * 0x09 — Cyclical Synchronous Torque.
     *
     * Каждая PDO обновляет целевой момент.
     *
     * Когда использовать: активное гашение вибраций,
     * сложное силовое управление. Нам не требуется.
     */
    CYCLIC_SYNC_TORQUE  (0x09),

    /**
     * 0x0A — Open Loop Oscillation (колебания без обратной связи).
     *
     * Двигатель выполняет синусоидальное движение с заданной
     * амплитудой и частотой — без энкодера. Используется
     * для механических тестов: поиск резонанса, жёсткости.
     *
     * Когда использовать: отладка механики, тестирование.
     * В штатной работе — никогда.
     */
    OPEN_LOOP           (0x0A);

    private final int value;

    OperationMode(int value) {
        this.value = value;
    }

    public int getValue() { return value; }

    @Override
    public String toString() {
        return String.format("%-20s (0x%02X)", name(), value);
    }
}
