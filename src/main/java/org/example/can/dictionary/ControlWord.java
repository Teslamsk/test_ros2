package org.example.can.dictionary;

import lombok.Getter;

/**
 * Control Word (0x6040) — главное "рулевое колесо" привода.
 * <p>
 * Это 16-битное слово, в которое мастер (наше ПО) записывает команду,
 * а слейв (движок на CAN) выполняет. Каждое значение — полная команда,
 * а не отдельный бит (за исключением битов статуса, которые слейв
 * записывает обратно в Status Word 0x6041).
 * <p>
 * Аналогия: представьте, что двигатель — это машина с автоматической КПП:
 * 1. Сначала заводите (shutdown),
 * 2. Снимаете с ручника (enable),
 * 3. Только потом жмёте газ (даёте позицию/скорость).
 * <p>
 * CiA 402 требует строгой последовательности — нельзя включить питание
 * и сразу дать момент. Поэтому используются промежуточные состояния.
 * <p>
 * Основные переходы:
 * DISABLE(0x0006) -> READY_TO_SWITCH_ON
 * ENABLE(0x0007)  -> OPERATION_ENABLED
 */
@Getter
public enum ControlWord {

    /**
     * 0x0000 — Полное отключение.
     * <p>
     * Снимает напряжение с обмоток двигателя. Двигатель "выключен" —
     * не держит позицию, не создаёт момента, можно крутить валик
     * пальцами как обычное колесо.
     * <p>
     * Когда использовать: отключение по окончании работы, после ошибки.
     * <p>
     * Результат: Status Word показывает "Switch On Disabled" (бит 1).
     */
    DISABLE(0x0000, "0x0000 — Полное отключение"),

    /**
     * 0x0006 — Подготовка (Shutdown).
     * <p>
     * Подача напряжения на драйвер, но без включения мощности. Двигатель
     * ещё не крутится и не держит позицию, но электроника привода
     * "просыпается": инициализирует энкодер, проверяет цепи, сообщает
     * через Status Word, что готова к работе.
     * <p>
     * Это обязательный первый шаг перед включением — нельзя перескокать
     * из DISABLE сразу в ENABLE.
     * <p>
     * Результат: Status Word показывает "Ready to Switch On" (бит 2).
     */
    SHUTDOWN(0x0006, "0x0006 — Подготовка (Shutdown)"),

    /**
     * 0x0007 — Включение (Enable).
     * <p>
     * Окончательный переход в рабочий режим. После этого двигатель
     * реагирует на команды позиционирования и крутящего момента.
     * Двигатель "на ходу" — если стоит режим позиции, он удержит
     * текущее положение.
     * <p>
     * Отправка: только после того, как Status Word показал
     * "Ready to Switch On". Иначе команда будет проигнорирована.
     * <p>
     * Результат: Status Word показывает "Operation Enabled" (бит 3).
     */
    ENABLE(0x0007, "0x0007 — Включение (Enable)"),

    /**
     * 0x000F — Полное включение со снятием блокировок.
     * <p>
     * Как ENABLE, но дополнительно снимает состояния Quick Release
     * и Disable Opc (запрет операции). Флаг "Operation Enabled"
     * остаётся активным.
     * <p>
     * Когда использовать: если после экстренной остановки (QUICK_STOP)
     * нужно вернуть привод в работу без полного цикла выключения.
     */
    ENABLE_FULL(0x000F, "0x000F — Полное включение со снятием блокировок."),

    /**
     * 0x001F — "Домой" (Homing) + полное включение.
     * <p>
     * Команда поиска нулевой позиции. Двигатель начинает движение
     * к механическому датчику нуля (если есть) или устанавливает
     * текущее положение за ноль. После завершения — двигатель
     * остаётся включённым в режиме позиционирования.
     * <p>
     * Когда использовать: калибровка после включения или ручной
     * установки лидара в начальное положение.
     * <p>
     * Результат: после завершения Status Word показывает бит
     * Target Reached (бит 13) + Operation Enabled (бит 3).
     */
    HOME(0x001F, "0x001F — \"Домой\" (Homing) + полное включение."),

    /**
     * 0x0020 — Быстрое освобождение (Quick Release).
     * <p>
     * Моментально снимает удержание позиции без остановки тока.
     * Двигатель перестаёт сопротивляться, но драйвер остаётся
     * включённым — можно сразу дать новую команду.
     * <p>
     * Отличие от DISABLE: после Quick Release можно быстро
     * вернуться к работе (ENABLE), а после DISABLE нужен полный
     * цикл SHUTDOWN → ENABLE.
     * <p>
     * Когда использовать: временная "отдача" двигателя рукам
     * на короткое время без выключения привода.
     */
    QUICK_RELEASE(0x0020, "0x0020 — Быстрое освобождение (Quick Release)."),

    /**
     * 0x0080 — Экстренная остановка (Quick Stop).
     * <p>
     * Двигатель тормозит по максимально допустимому замедлению
     * (без инерционного перелёта), но без постановки в ошибку (Fault).
     * Ток снимается моментально, но состояние привода остаётся
     * "живым" — после снятия Quick Stop можно продолжить работу
     * (переходим в Switch On Disabled → ещё раз SHUTDOWN → ENABLE).
     * <p>
     * Важно: нужно отправить Quick Stop дважды, чтобы "разблокировать"
     * — так CiA 402 защищает от случайного снятия стопа.
     * <p>
     * Когда использовать: кнопка аварийной остановки, препятствие
     * в зоне сканирования, критическая ошибка.
     * <p>
     * Результат: Status Word показывает "Fast Stop" (бит 10).
     */
    QUICK_STOP(0x0080, "0x0080 — Экстренная остановка (Quick Stop)"),

    /**
     * 0x0081 — Снятие экстренной остановки (Reset Quick Stop).
     * <p>
     * Второе нажатие "красной кнопки" — разблокирует состояние
     * Quick Stop, установленное значением 0x0080. После этого
     * двигатель переходит в "Switch On Disabled" (0x0000).
     * <p>
     * Полное восстановление: QUICK_STOP(0x0080) → TOGGLE_QUICK_STOP(0x0081)
     * → SHUTDOWN(0x0006) → ENABLE(0x0007).
     * <p>
     * Когда использовать: после экстренной остановки, когда опасность
     * устранена.
     */
    TOGGLE_QUICK_STOP(0x0081, "0x0081 — Снятие экстренной остановки (Reset Quick Stop).");

    private final int value;
    private final String description;

    ControlWord(int value, String description) {
        this.value = value;
        this.description = description;
    }

    public int getValue() {
        return value;
    }

    @Override
    public String toString() {
        return String.format("%s (0x%04X)", name(), value);
    }
}
