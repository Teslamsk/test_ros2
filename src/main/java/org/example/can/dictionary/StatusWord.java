package org.example.can.dictionary;

/**
 * Status Word (0x6041) — "отчёт" привода о своём состоянии.
 *
 * Slave (двигатель) постоянно пишет сюда 16-битное слово, а master
 * (наше ПО) читает и по установленным битам понимает, что происходит.
 *
 * Это не команда — это обратная связь. Control Word мы _пишем_,
 * Status Word мы _читаем_ (или слушаем через TPDO).
 *
 * Биты работают как флаги — только один из битов 0–3 может быть
 * активен одновременно (они взаимоисключающие, представляют текущее
 * состояние конечного автомата CiA 402). Остальные биты независимы.
 *
 * Типичный путь "запуска машины":
 *   NOT_READY (бит 0) -> SWITCH_ON_DISABLED (бит 1) -> READY_TO_SWITCH_ON (бит 2) -> OPERATION_ENABLED (бит 3)
 */
public enum StatusWord {

    /**
     * Бит 0 (0x0001) — Not Ready To Switch On.
     *
     * Привод включился в сеть, но ещё не прошёл инициализацию:
     * калибрует энкодер, загружает параметры, проверяет цепи.
     * В этом состоянии никакие команды не принимаются.
     *
     * Как понять: "двигатель включается, подождите".
     */
    NOT_READY_TO_SWITCH_ON (0x0001),

    /**
     * Бит 1 (0x0002) — Switch On Disabled.
     *
     * Инициализация пройдена, но напряжение на обмотки не подано.
     * Двигатель "сидит": не крутится, не держит позицию,
     * не потребляет рабочую мощность.
     *
     * Как понять: "включен, заряжен, но не запущен".
     */
    SWITCH_ON_DISABLED     (0x0002),

    /**
     * Бит 2 (0x0004) — Ready To Switch On.
     *
     * Промежуточное состояние перед стартом. Напряжение подано,
     * драйвер готов, но рабочий режим ещё не активирован.
     *
     * Как понять: "готов к работе, ждем команду".
     */
    READY_TO_SWITCH_ON     (0x0004),

    /**
     * Бит 3 (0x0008) — Operation Enabled.
     *
     * Рабочий режим: двигатель выполняет команды (позицию/скорость/момент).
     * Если это режим позиционирования — двигатель удерживает текущий угол.
     *
     * Как понять: "работает, выполняет задачи".
     */
    OPERATION_ENABLED      (0x0008),

    /**
     * Бит 4 (0x0010) — Voltage Enabled.
     *
     * Напряжение на питание привода подано (включены драйверы).
     * Устанавливается при переходе из Not Ready в Switch On Disabled.
     *
     * Как понять: "силовая часть под напряжением".
     */
    VOLTAGE_ENABLED        (0x0010),

    /**
     * Бит 5 (0x0020) — Fault.
     *
     * Критическая ошибка. Привод ушёл в аварийное состояние:
     * перегрев, перенапряжение, сбой энкодера, короткое замыкание и т.д.
     *
     * Для сброса нужно: Control Word = 0x80 (Quick Stop),
     * затем Control Word = 0x81 (Toggle Quick Stop),
     * затем повторный запуск (Shutdown -> Enable).
     *
     * Как понять: "КРАСНАЯ ЛАМПА — авария!".
     */
    FAULT                  (0x0020),

    /**
     * Бит 10 (0x0400) — Fast Stopped.
     *
     * Двигатель получил команду экстренной остановки (Quick Stop).
     * Замедляется по максимальному профилю. Не является ошибкой:
     * можно снять Quick Stop и продолжить работу.
     *
     * Как понять: "аварийно остановлен, но не сломался".
     */
    FAST_STOPPED           (0x0400),

    /**
     * Бит 13 (0x0800) — Target Reached.
     *
     * Двигатель добрался до целевой позиции с заданной точностью
     * (позиционное окно = 0x60CB). Остается в этой позиции,
     * пока не придет новая команда.
     *
     * Как понять: "дошел! Готов к следующей команде".
     */
    TARGET_REACHED         (0x0800),

    /**
     * Бит 14 (0x1000) — Manual Request.
     *
     * Флаг для взаимодействия с ручным управлением.
     * В контексте CiA 402 используется редко, обычно
     * зависит от конкретного привода.
     *
     * Как понять: "ручной режим активирован".
     */
    MANUAL_REQUEST         (0x1000),

    /**
     * Бит 15 (0x8000) — Remote.
     *
     * Привод управляется удаленно (через NMT из CANopen), а не
     * локально (кнопки на корпусе устройства). В нормальной
     * работе всегда установлен.
     *
     * Как понять: "управляется по CAN, а не кнопками".
     */
    REMOTE                 (0x8000);

    private final int value;

    StatusWord(int value) {
        this.value = value;
    }

    public int getValue() { return value; }

    /**
     * Проверяет, установлен ли этот бит в полученном статусном слове.
     */
    public boolean isSet(int statusWordValue) {
        return (statusWordValue & value) != 0;
    }


    @Override
    public String toString() {
        return String.format("%-22s (bit %d, 0x%04X)", name(), Integer.numberOfTrailingZeros(value), value);
    }
}
